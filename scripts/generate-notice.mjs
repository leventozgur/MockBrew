// Regenerates NOTICE.md from the installed production dependency tree.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const listing = execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
const packages = new Map();
for (const dir of listing.split('\n').filter(Boolean)) {
  const file = path.join(dir, 'package.json');
  if (!existsSync(file)) continue;
  const json = JSON.parse(readFileSync(file, 'utf8'));
  if (!json.name || dir === root) continue;
  const license = typeof json.license === 'object' ? json.license.type : (json.license ?? json.licenses?.map((l) => l.type).join(' OR ') ?? 'UNKNOWN');
  packages.set(`${json.name}@${json.version}`, license);
}

const mockoonLicense = readFileSync(path.join(root, 'node_modules/@mockoon/commons-server/LICENSE.md'), 'utf8').trim();
const rows = [...packages.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([name, license]) => `| ${name} | ${license} |`);

const text = `# Third-party notices

MockBrew is an independent tool. It is not a fork or an extension of Mockoon and is not affiliated
with Mockoon. It uses the Mockoon mock engine (\`@mockoon/commons\` and \`@mockoon/commons-server\`) as a library.

## Mockoon

\`@mockoon/commons\` and \`@mockoon/commons-server\` are distributed under the MIT License:

\`\`\`
${mockoonLicense}
\`\`\`

## Syntax grammars

The Kotlin and Swift grammars are loaded from \`tree-sitter-wasms\` (public domain packaging) and are compiled from
the open source tree-sitter grammars for Kotlin and Swift (MIT). The runtime is \`web-tree-sitter\` (MIT).

## Weak copyleft dependency

\`@jmespath-community/jmespath\` (MPL-2.0) is a dependency of the Mockoon engine. It is used unmodified; its source is
available from the npm package and the project at https://github.com/jmespath-community/typescript-jmespath.

## Runtime dependencies

Generated by \`npm run notice\` from the installed production dependency tree (${packages.size} packages).

| Package | License |
| --- | --- |
${rows.join('\n')}
`;

writeFileSync(path.join(root, 'NOTICE.md'), text);
console.log(`NOTICE.md written with ${packages.size} packages`);
