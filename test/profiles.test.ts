import { promises as fs } from 'node:fs';
import net from 'node:net';
import os from 'node:os';
import path from 'node:path';
import { afterEach, expect, it } from 'vitest';
import { ProjectService } from '../src/core/service.js';

let service: ProjectService | undefined;
let dir = '';
afterEach(async () => { await service?.close(); service = undefined; if (dir) await fs.rm(dir, { recursive: true, force: true }); });

it('applies profiles to live HTTP, honors overrides, restores selections, and reports stale references', async () => {
  const listener = net.createServer();
  await new Promise<void>((resolve) => listener.listen(0, '127.0.0.1', resolve));
  const port = (listener.address() as net.AddressInfo).port;
  await new Promise<void>((resolve) => listener.close(() => resolve()));
  dir = await fs.mkdtemp(path.join(os.tmpdir(), 'mockbrew-profiles-'));
  service = await ProjectService.init(dir, 'Profiles', { port });
  const a = await service.createEndpoint('root', { method: 'GET', path: '/a', scenarios: [{ name: 'OK', body: '{}' }] });
  const b = await service.createEndpoint('root', { method: 'GET', path: '/b', scenarios: [{ name: 'OK', body: '{}' }] });
  const a401 = await service.createScenario(a, { name: 'Expired', statusCode: 401, body: '{}' });
  const b401 = await service.createScenario(b, { name: 'Expired', statusCode: 401, body: '{}' });
  await service.setScenarioRules(a, service.findEndpoint(a).scenarios[0]!.id, [{ target: 'query', modifier: 'force', value: 'yes', operator: 'equals', invert: false }], 'AND');
  const id = await service.saveProfile({ name: 'Session expired', endpoints: { [a]: { scenarioId: a401 }, [b]: { scenarioId: b401 } }, network: { latencyMs: 40, timeoutEndpoints: [b], timeoutMs: 300 } });
  await service.start();
  const base = service.runtime.status().url;
  expect((await fetch(`${base}/a`)).status).toBe(200);
  await service.activateProfile(id);
  const start = Date.now();
  expect((await fetch(`${base}/a?force=yes`)).status).toBe(401);
  expect(Date.now() - start).toBeGreaterThanOrEqual(40);
  const catchAllStart = Date.now();
  expect((await fetch(`${base}/missing`)).status).toBe(404);
  expect(Date.now() - catchAllStart).toBeGreaterThanOrEqual(40);
  expect((await fetch(`${base}/a`, { headers: { 'X-Mock-Scenario': 'OK' } })).status).toBe(200);
  await expect(fetch(`${base}/b`, { signal: AbortSignal.timeout(100) })).rejects.toThrow();
  expect(service.runtime.logs().some((l) => l.profile === 'Session expired' && l.scenarioReason === 'profile')).toBe(true);
  await service.deactivateProfile();
  expect((await fetch(`${base}/a`)).status).toBe(200);
  expect((await fetch(`${base}/b`)).status).toBe(200);
  await expect(service.saveProfile({ name: 'SESSION EXPIRED', endpoints: {} })).rejects.toThrow(/unique/);
  await expect(service.saveProfile({ name: 'Invalid', endpoints: { missing: { scenarioId: 'missing' } } })).rejects.toThrow(/reference/);
  await service.deleteEndpoint(a);
  expect(service.listProfiles().profiles[0]?.staleReferences).toContain(a);
  await service.activateProfile(id);
  expect((await fetch(`${base}/b`, { signal: AbortSignal.timeout(100) }).catch(() => null))).toBeNull();
  await service.deactivateProfile();
  await service.close();
  service = await ProjectService.open(dir);
  expect(service.listProfiles().profiles[0]).toMatchObject({ id, name: 'Session expired', staleReferences: [a] });
});
